const GLYPH_W = 5;
const GLYPH_H = 7;

/** What the watermark says: the phone's name and the UTC time, to the second. */
export function labelFor(name, at = new Date()) {
  const who =
    String(name ?? "")
      .replace(/\s+/g, " ")
      .trim() || "Phone";
  return `${who} ${at.toISOString().replace(/\.\d{3}Z$/, "Z")}`;
}

/** [text] truncated to what [width] can hold at [scale]. */
export function fitLabel(text, width, scale) {
  const room = Math.max(1, Math.floor((width - 16) / ((GLYPH_W + 1) * scale)));
  return String(text).slice(0, room);
}

/**
 * Draw [text] into a BGRX [frame] along the bottom-left: a darkened strip, white glyphs. The
 * scale follows the frame width so the mark stays legible on small phone frames and on 4K.
 * Returns the text actually drawn, or "" when the frame is too small to mark.
 */
export function stamp(frame, width, height, text) {
  const scale = Math.max(1, Math.min(3, Math.round(width / 960) || 1));
  const pad = 4 * scale;
  const stripH = GLYPH_H * scale + pad * 2;
  if (!frame || width < 40 || height < stripH + pad || frame.length < width * height * 4) return "";
  const shown = fitLabel(text, width, scale);
  const x0 = pad;
  const y0 = height - stripH - pad;
  // Darken the strip so white text reads on both a bright and a dark picture.
  for (let y = y0; y < y0 + stripH; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4;
      frame[i] = (frame[i] * 0.35) | 0;
      frame[i + 1] = (frame[i + 1] * 0.35) | 0;
      frame[i + 2] = (frame[i + 2] * 0.35) | 0;
    }
  }
  const step = (GLYPH_W + 1) * scale;
  for (let c = 0; c < shown.length; c++) {
    const glyph = GLYPHS[shown[c].toUpperCase()] || GLYPHS["?"];
    const gx = x0 + c * step;
    if (gx + GLYPH_W * scale > width) break;
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = glyph[row];
      for (let col = 0; col < GLYPH_W; col++) {
        if (!(bits & (1 << (GLYPH_W - 1 - col)))) continue;
        for (let dy = 0; dy < scale; dy++) {
          const y = y0 + pad + row * scale + dy;
          for (let dx = 0; dx < scale; dx++) {
            const x = gx + col * scale + dx;
            const i = (y * width + x) * 4;
            frame[i] = 255;
            frame[i + 1] = 255;
            frame[i + 2] = 255;
          }
        }
      }
    }
  }
  return shown;
}
