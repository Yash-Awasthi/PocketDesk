#!/usr/bin/env node
// Generates the protocol table in daemon/README.md from the handler registry.
//
// `handle()` dispatches on `handlers[msg.type]`, and every handler module is a factory
// that returns an object of message types. This script asks each factory for its keys
// (with a stub context, so nothing is started) and writes one row per message.
//
//   node daemon/scripts/gen-protocol-doc.mjs           # rewrite the table
//   node daemon/scripts/gen-protocol-doc.mjs --check   # exit 1 when the table is stale
//
// daemon/test/protocol-doc.test.mjs runs the --check form, so the table cannot drift.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DAEMON = path.dirname(HERE);
const README = path.join(DAEMON, "README.md");
const BEGIN = "<!-- BEGIN protocol-table -->";
const END = "<!-- END protocol-table -->";

// A context that answers any property with a callable no-op or another stub, so the
// factories can build their objects without a running server.
function stubCtx() {
  const fn = () => stubCtx();
  return new Proxy(fn, {
    get: (_t, prop) => (prop === "then" ? undefined : stubCtx()),
    apply: () => stubCtx(),
  });
}

// Some modules export their handlers as the default factory; a few also export helpers.
async function handlerKeys(file) {
  const mod = await import(
    new URL(`file://${path.join(DAEMON, "src", "handlers", file).replace(/\\/g, "/")}`)
  );
  const factory = mod.default;
  const out = new Set();
  if (typeof factory === "function") {
    const produced = factory(stubCtx());
    if (produced && typeof produced === "object") for (const k of Object.keys(produced)) out.add(k);
  }
  return out;
}

const dir = path.join(DAEMON, "src", "handlers");
const rows = [];
for (const file of fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".js"))
  .sort()) {
  let keys;
  try {
    keys = await handlerKeys(file);
  } catch (e) {
    // Fall back to reading the object literal: a factory that needs a live server still
    // declares its message names as four-space-indented methods.
    const text = fs.readFileSync(path.join(dir, file), "utf8");
    keys = new Set([...text.matchAll(/^\s{4}(?:async\s+)?([a-z][a-z0-9_]*)\s*\(/gm)].map((m) => m[1]));
    console.error(
      `gen-protocol-doc: ${file} could not be instantiated (${e.message.split("\n")[0]}); read statically`,
    );
  }
  for (const k of keys) rows.push({ type: k, file: `src/handlers/${file}` });
}

// Handlers added straight onto the map in server.js (loopback-only pages, the DAV drive).
const serverText = fs.readFileSync(path.join(DAEMON, "src", "server.js"), "utf8");
for (const m of serverText.matchAll(/handlers\.([a-z][a-z0-9_]*)\s*=/g))
  rows.push({ type: m[1], file: "src/server.js" });

rows.sort((a, b) => a.type.localeCompare(b.type) || a.file.localeCompare(b.file));

const table = [
  BEGIN,
  "",
  `Generated by \`node daemon/scripts/gen-protocol-doc.mjs\` — ${rows.length} message types, one row each.`,
  "Do not edit by hand: `daemon/test/protocol-doc.test.mjs` fails when this is stale.",
  "",
  "| Message | Handler |",
  "|---|---|",
  ...rows.map((r) => `| \`${r.type}\` | \`${r.file}\` |`),
  "",
  END,
].join("\n");

const current = fs.existsSync(README) ? fs.readFileSync(README, "utf8") : "";
const header = current.includes(BEGIN)
  ? current.slice(0, current.indexOf(BEGIN))
  : `${current.trimEnd()}\n\n## Protocol messages\n\nThe table below is generated from the handler registry, so every message the daemon\nanswers appears exactly once, with the file that answers it.\n\n`;
const next = `${header}${table}\n${current.includes(END) ? current.slice(current.indexOf(END) + END.length).replace(/^\r?\n/, "") : ""}`;

if (process.argv.includes("--check")) {
  const normal = (s) => s.replace(/\r\n/g, "\n").trimEnd();
  if (normal(current) !== normal(next)) {
    console.error("daemon/README.md protocol table is stale — run: node daemon/scripts/gen-protocol-doc.mjs");
    process.exit(1);
  }
  console.log(`protocol table is current (${rows.length} message types)`);
} else {
  fs.writeFileSync(README, next);
  console.log(`wrote ${rows.length} message types to daemon/README.md`);
}
